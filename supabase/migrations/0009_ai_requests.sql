-- Ligera migration 0009
-- Per-user quota for the AI exercise-classification endpoint.
-- Only user_id, kind and timestamp are stored: never the exercise name.
-- Run once in the Supabase SQL Editor.

create table if not exists public.ai_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null default 'classify',
  created_at timestamptz not null default now()
);

create index if not exists ai_requests_user_created_idx
  on public.ai_requests (user_id, created_at desc);

alter table public.ai_requests enable row level security;

drop policy if exists "ai_requests_select_own" on public.ai_requests;
create policy "ai_requests_select_own"
  on public.ai_requests for select
  to authenticated
  using (auth.uid() = user_id);

create or replace function public.consume_ai_quota(p_daily_limit integer default 20)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  used integer;
  limit_value integer := greatest(coalesce(p_daily_limit, 20), 1);
begin
  if uid is null then
    raise exception 'Not authenticated';
  end if;

  delete from public.ai_requests
   where user_id = uid
     and created_at < now() - interval '30 days';

  select count(*) into used
    from public.ai_requests
   where user_id = uid
     and created_at >= date_trunc('day', now());

  if used >= limit_value then
    return jsonb_build_object('allowed', false, 'remaining', 0);
  end if;

  insert into public.ai_requests (user_id, kind) values (uid, 'classify');

  return jsonb_build_object('allowed', true, 'remaining', limit_value - used - 1);
end;
$$;

revoke execute on function public.consume_ai_quota(integer) from public, anon;
grant execute on function public.consume_ai_quota(integer) to authenticated, service_role;
